export function getTeamColors(code) {
  return teamThemeColors[code] || null;
}

export function getAllTeamsWithColors(worldCupTeamsByGroup) {
  const teams = [];
  let pageIndex = 1;

  Object.entries(worldCupTeamsByGroup).forEach(([groupName, groupTeams]) => {
    groupTeams.forEach(team => {
      teams.push({
        ...team,
        groupName,
        pageIndex: pageIndex++,
        colors: teamThemeColors[team.code] || null
      });
    });
  });

  return teams;
}

